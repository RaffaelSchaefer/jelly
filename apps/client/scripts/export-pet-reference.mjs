// Schreibt die prozedurale Geometrie des Pets (packages/jelly-scene/src/jellyGeometry.ts) als
// blender/pet_reference.obj, den Referenzkörper, um den die Cosmetics modelliert werden.
// Aufruf: pnpm blender:reference
// Einheiten und Achsen wie in der App (y nach oben, vorn +z). Blenders OBJ-Import dreht auf z oben.

import {
  createBodyGeometry,
  createHandGeometry,
  createHeadGeometry,
  HAND,
} from "@jelly/scene/geometry";
import { writeFileSync } from "node:fs";

const hand = (side) => createHandGeometry().translate(side * HAND.x, HAND.y, HAND.z);
const parts = {
  body: createBodyGeometry(),
  head: createHeadGeometry(),
  hand_left: hand(-1),
  hand_right: hand(1),
};

const lines = ["# Jelly reference, generated by scripts/export-pet-reference.mjs. Do not edit."];
let offset = 1;
for (const [name, geometry] of Object.entries(parts)) {
  const position = geometry.getAttribute("position");
  const normal = geometry.getAttribute("normal");
  const index = geometry.getIndex();
  lines.push(`o ${name}`);
  for (let i = 0; i < position.count; i++)
    lines.push(
      `v ${position.getX(i).toFixed(5)} ${position.getY(i).toFixed(5)} ${position.getZ(i).toFixed(5)}`,
    );
  for (let i = 0; i < normal.count; i++)
    lines.push(
      `vn ${normal.getX(i).toFixed(5)} ${normal.getY(i).toFixed(5)} ${normal.getZ(i).toFixed(5)}`,
    );
  lines.push("s 1");
  for (let i = 0; i < index.count; i += 3) {
    const [a, b, c] = [index.getX(i), index.getX(i + 1), index.getX(i + 2)].map((v) => v + offset);
    lines.push(`f ${a}//${a} ${b}//${b} ${c}//${c}`);
  }
  offset += position.count;
}
writeFileSync(new URL("../blender/pet_reference.obj", import.meta.url), `${lines.join("\n")}\n`);
console.log(`blender/pet_reference.obj: ${Object.keys(parts).join(", ")}`);
