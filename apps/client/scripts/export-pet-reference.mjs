// Writes the pet's procedural geometry (src/jellyGeometry.ts) as blender/pet_reference.obj,
// the reference body cosmetics are modelled on. Usage: npm run blender:reference
// Units and axes are the app's (Y up, front +Z); Blender's OBJ importer turns them Z up.
import { writeFileSync } from 'node:fs';
import { createBodyGeometry, createHandGeometry, createHeadGeometry, HAND } from '../src/jellyGeometry.ts';

const hand = (side) => createHandGeometry().translate(side * HAND.x, HAND.y, HAND.z);
const parts = { body: createBodyGeometry(), head: createHeadGeometry(), hand_left: hand(-1), hand_right: hand(1) };

const lines = ['# LAN Desk Pet reference, generated by scripts/export-pet-reference.mjs. Do not edit.'];
let offset = 1;
for (const [name, geometry] of Object.entries(parts)) {
  const position = geometry.getAttribute('position');
  const normal = geometry.getAttribute('normal');
  const index = geometry.getIndex();
  lines.push(`o ${name}`);
  for (let i = 0; i < position.count; i++) lines.push(`v ${position.getX(i).toFixed(5)} ${position.getY(i).toFixed(5)} ${position.getZ(i).toFixed(5)}`);
  for (let i = 0; i < normal.count; i++) lines.push(`vn ${normal.getX(i).toFixed(5)} ${normal.getY(i).toFixed(5)} ${normal.getZ(i).toFixed(5)}`);
  lines.push('s 1');
  for (let i = 0; i < index.count; i += 3) {
    const [a, b, c] = [index.getX(i), index.getX(i + 1), index.getX(i + 2)].map((v) => v + offset);
    lines.push(`f ${a}//${a} ${b}//${b} ${c}//${c}`);
  }
  offset += position.count;
}
writeFileSync(new URL('../blender/pet_reference.obj', import.meta.url), `${lines.join('\n')}\n`);
console.log(`blender/pet_reference.obj: ${Object.keys(parts).join(', ')}`);
